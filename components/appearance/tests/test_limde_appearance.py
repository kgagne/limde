"""Run limde-appearance in a temporary home with a stand-in gsettings: --output-dir, the
diff, --check, --apply, the user file, errors and --mode. Never touches the real home or
desktop preferences, and needs neither the icon themes nor a desktop session."""
from pathlib import Path
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import tomllib
import unittest

HERE = Path(__file__).resolve().parents[1]
SCRIPT = HERE / "limde-appearance"
DEFAULTS = tomllib.loads((HERE / "appearance.toml").read_text())
MANIFEST = tomllib.loads((HERE / "manifest.toml").read_text())
OUTPUTS = {Path(entry["destination"]) for entry in MANIFEST["files"]}
TINYBAR_CSS = Path(".config/tinybar/style.css")
GTK3_SETTINGS = Path(".config/gtk-3.0/settings.ini")


def panel_background(css):
    """The panel's own background, the first rule of tinybar.css.in (colour values repeat
    across keys, so a bare search for one proves little)."""
    return re.search(r"^window \{\s*background: (#[0-9A-Fa-f]+);", css, re.M).group(1)


# get/set SCHEMA KEY [VALUE]; values are kept as files, quoted the way gsettings prints
# them. FAKE_GSETTINGS picks a failure: noschema (get fails, as without the schemas),
# lose (set succeeds but keeps nothing) or refuse (set fails).
STAND_IN_GSETTINGS = """#!/bin/sh
[ "$2" = org.gnome.desktop.interface ] || exit 1
file="$FAKE_GSETTINGS_DIR/$3"
case "$1:$FAKE_GSETTINGS" in
  get:noschema) echo 'No such schema' >&2; exit 1 ;;
  get:*) if [ -f "$file" ]; then cat "$file"; else echo "''"; fi ;;
  set:lose) ;;
  set:refuse) echo 'gsettings: writing is not allowed' >&2; exit 1 ;;
  set:*) printf "'%s'\\n" "$4" > "$file" ;;
  *) exit 1 ;;
esac
"""


class AppearanceTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.home, self.settings = self.root / "home", self.root / "gsettings"
        self.bin = self.root / "bin"
        for folder in (self.home, self.settings, self.bin):
            folder.mkdir()
        fake = self.bin / "gsettings"
        fake.write_text(STAND_IN_GSETTINGS)
        fake.chmod(0o755)
        # The memory backend keeps even a real gsettings away from dconf.
        self.env = dict(os.environ, HOME=str(self.home), PATH=f"{self.bin}:{os.environ['PATH']}",
                        GSETTINGS_BACKEND="memory", FAKE_GSETTINGS="",
                        FAKE_GSETTINGS_DIR=str(self.settings))
        self.assertEqual(shutil.which("gsettings", path=self.env["PATH"]), str(fake))
        self.user_file = self.home / ".config/limde/appearance.toml"
        self.state = self.home / ".local/state/limde/appearance"
        self.mode_file = self.state / "mode"

    def run_tool(self, *args, **env):
        result = subprocess.run([sys.executable, "-B", str(SCRIPT), *args],
                                env={**self.env, **env}, capture_output=True, text=True, timeout=60)
        self.assertNotIn("Traceback", result.stderr)
        return result

    def apply(self, *args, **env):
        result = self.run_tool("--apply", *args, **env)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        return result

    def files(self, root):
        return {p.relative_to(root) for p in root.rglob("*") if p.is_file()}

    def setting(self, key):
        path = self.settings / key
        return path.read_text().strip() if path.is_file() else None

    def write_user_file(self, text):
        self.user_file.parent.mkdir(parents=True, exist_ok=True)
        self.user_file.write_text(text)

    def backups(self):
        folder = self.state / "backups"
        return sorted(folder.iterdir()) if folder.is_dir() else []

    def test_output_dir_renders_every_template_and_nothing_else(self):
        out = self.root / "out"
        result = self.run_tool("--output-dir", str(out))
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(result.stdout.strip(), f"Rendered {len(OUTPUTS)} files in {out}")
        self.assertEqual(self.files(out), OUTPUTS)
        self.assertEqual(list(self.home.iterdir()), [])
        self.assertEqual(list(self.settings.iterdir()), [])
        css = (out / TINYBAR_CSS).read_text()
        self.assertTrue(css.startswith("/* Generated by limde-appearance from templates/tinybar.css.in"))
        self.assertEqual(panel_background(css), DEFAULTS["colors"]["background"])
        self.assertNotIn("${", css)

    def test_diff_shows_the_change_and_writes_nothing(self):
        result = self.run_tool()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn(f"+++ {self.home / TINYBAR_CSS}", result.stdout)
        self.assertIn("Desktop preference needs refresh: icon-theme '' -> limde", result.stdout)
        self.assertEqual(list(self.home.iterdir()), [])
        self.assertEqual(list(self.settings.iterdir()), [])

    def test_apply_then_check_match(self):
        before = self.run_tool("--check")
        self.assertEqual(before.returncode, 1, before.stderr)
        self.assertEqual(before.stdout.count("Needs refresh:"), len(OUTPUTS))
        self.assertIn("Desktop preference needs refresh: color-scheme '' -> prefer-dark", before.stdout)
        self.assertEqual(list(self.home.iterdir()), [])

        applied = self.apply()
        self.assertEqual(applied.stdout.count("Updated: "), len(OUTPUTS))
        self.assertTrue(OUTPUTS <= self.files(self.home))
        self.assertEqual(self.setting("icon-theme"), "'limde'")
        self.assertEqual(self.setting("gtk-theme"), "'LimDE'")
        self.assertEqual(self.setting("color-scheme"), "'prefer-dark'")
        self.assertEqual(self.setting("font-name"), repr(DEFAULTS["fonts"]["interface"]))
        self.assertEqual(self.setting("document-font-name"), repr(DEFAULTS["fonts"]["document"]))
        # Nothing existed to back up but the preferences, kept in one folder per run.
        [backup] = self.backups()
        self.assertIn(f"Previous versions saved in {backup}", applied.stdout)
        before_prefs = json.loads((backup / "desktop-preferences.before.json").read_text())
        self.assertEqual(before_prefs["icon-theme"], {"before": "''", "after": "limde"})
        self.assertFalse(self.mode_file.exists())

        after = self.run_tool("--check")
        self.assertEqual(after.returncode, 0, after.stdout + after.stderr)
        self.assertEqual(after.stdout.strip(),
                         f"All {len(OUTPUTS)} files and desktop preferences are current.")
        again = self.apply()
        self.assertEqual(again.stdout.strip(), "Everything is already current.")
        self.assertEqual(len(self.backups()), 1)

    def test_check_reports_a_hand_edited_output_and_apply_backs_it_up(self):
        self.apply()
        edited = self.home / TINYBAR_CSS
        edited.write_text(edited.read_text() + "/* local edit */\n")
        result = self.run_tool("--check")
        self.assertEqual(result.returncode, 1)
        self.assertEqual(result.stdout.strip(), f"Needs refresh: {edited}")
        fixed = self.apply()
        self.assertEqual(fixed.stdout.splitlines()[0], f"Updated: {edited}")
        self.assertNotIn("local edit", edited.read_text())
        saved = self.backups()[-1] / TINYBAR_CSS
        self.assertIn("local edit", saved.read_text())

    def test_a_symlinked_output_is_left_for_review(self):
        target = self.home / TINYBAR_CSS
        target.parent.mkdir(parents=True)
        target.symlink_to(self.root / "elsewhere.css")
        result = self.run_tool("--apply")
        self.assertEqual(result.returncode, 1)
        self.assertEqual(result.stderr.strip(),
                         f"limde-appearance: review this symlink before replacing it: {target}")
        self.assertFalse((self.root / "elsewhere.css").exists())

    def test_user_file_changes_only_its_keys(self):
        self.write_user_file('[colors]\nbackground = "#102030"\n\n'
                             '[fonts]\ninterface = "Test Sans 10"\n\n'
                             '# Older files set this; it is ignored now.\n'
                             '[desktop]\ncolor_scheme = "prefer-light"\n')
        self.apply()
        css = (self.home / TINYBAR_CSS).read_text()
        self.assertEqual(panel_background(css), "#102030")
        self.assertIn(f"background: {DEFAULTS['colors']['surface']};", css)
        self.assertEqual(self.setting("font-name"), "'Test Sans 10'")
        self.assertEqual(self.setting("document-font-name"), repr(DEFAULTS["fonts"]["document"]))
        self.assertEqual(self.setting("color-scheme"), "'prefer-dark'")
        self.assertEqual(self.run_tool("--check").returncode, 0)

    def test_unknown_or_invalid_settings_are_one_line_errors(self):
        cases = [
            ("[nosuch]\nkey = 1\n", f"{self.user_file}: unknown group [nosuch]"),
            ('colors = "#000000"\n', f"{self.user_file}: unknown group [colors]"),
            ('[colors]\nnosuch = "#000000"\n', f"{self.user_file}: unknown setting colors.nosuch"),
            ('[colors]\nbackground = "black"\n', "invalid value for colors.background: 'black'"),
            ('[desktop]\nmode = "sepia"\n', "invalid value for desktop.mode: 'sepia'"),
            ('[fonts]\ninterface = "Open Sans"\n', "invalid value for fonts.interface: 'Open Sans'"),
        ]
        for text, error in cases:
            with self.subTest(text=text):
                self.write_user_file(text)
                for args in (("--apply",), ("--check",), ("--output-dir", str(self.root / "out"))):
                    result = self.run_tool(*args)
                    self.assertEqual(result.returncode, 1, args)
                    self.assertEqual(result.stderr, f"limde-appearance: {error}\n", args)
                self.assertEqual(list(self.home.iterdir()), [self.home / ".config"])
                self.assertEqual(list(self.settings.iterdir()), [])
        self.write_user_file("[colors\n")
        result = self.run_tool("--check")
        self.assertEqual(result.returncode, 1)
        self.assertTrue(result.stderr.startswith("limde-appearance: "), result.stderr)
        self.assertEqual(len(result.stderr.splitlines()), 1, result.stderr)

    def test_mode_switch_is_kept_in_the_mode_file(self):
        self.assertEqual(self.run_tool("--mode", "light").returncode, 2)  # needs --apply
        self.apply()
        light = self.apply("--mode", "light")
        self.assertIn(f"Updated: {self.home / TINYBAR_CSS}", light.stdout)
        self.assertEqual(self.mode_file.read_text(), "light\n")
        css = (self.home / TINYBAR_CSS).read_text()
        self.assertEqual(panel_background(css), DEFAULTS["colors_light"]["background"])
        self.assertIn("gtk-icon-theme-name=limde-light", (self.home / GTK3_SETTINGS).read_text())
        self.assertEqual(self.setting("color-scheme"), "'prefer-light'")
        self.assertEqual(self.setting("icon-theme"), "'limde-light'")
        # The saved choice wins over the defaults and the user file, without --mode.
        self.assertEqual(self.run_tool("--check").returncode, 0)
        self.write_user_file('[desktop]\nmode = "dark"\n')
        self.assertEqual(self.run_tool("--check").returncode, 0)
        out = self.root / "out"
        self.assertEqual(self.run_tool("--output-dir", str(out)).returncode, 0)
        self.assertEqual(panel_background((out / TINYBAR_CSS).read_text()),
                         DEFAULTS["colors_light"]["background"])

        self.apply("--mode", "dark")
        self.assertEqual(self.mode_file.read_text(), "dark\n")
        self.assertEqual(panel_background((self.home / TINYBAR_CSS).read_text()),
                         DEFAULTS["colors"]["background"])
        self.assertEqual(self.setting("color-scheme"), "'prefer-dark'")
        self.assertEqual(self.setting("icon-theme"), "'limde'")

    def test_a_bad_mode_file_is_ignored(self):
        self.write_user_file('[desktop]\nmode = "light"\n')
        self.apply()
        self.mode_file.parent.mkdir(parents=True, exist_ok=True)
        for text in ("sepia\n", "", "dark light\n"):
            with self.subTest(text=text):
                self.mode_file.write_text(text)
                result = self.run_tool("--check")
                self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertEqual(self.setting("color-scheme"), "'prefer-light'")
        # --mode replaces it.
        self.apply("--mode", "dark")
        self.assertEqual(self.mode_file.read_text(), "dark\n")

    def test_without_gsettings_or_its_schema_only_the_files_are_written(self):
        for env in ({"PATH": str(self.root / "empty")}, {"FAKE_GSETTINGS": "noschema"}):
            with self.subTest(env=env):
                shutil.rmtree(self.home)
                self.home.mkdir()
                applied = self.apply(**env)
                self.assertNotIn("desktop preference", applied.stdout)
                self.assertTrue(OUTPUTS <= self.files(self.home))
                self.assertEqual(list(self.settings.iterdir()), [])
                check = self.run_tool("--check", **env)
                self.assertEqual(check.returncode, 0, check.stdout + check.stderr)

    def test_a_preference_that_does_not_persist_fails_the_apply(self):
        result = self.run_tool("--apply", "--mode", "light", FAKE_GSETTINGS="lose")
        self.assertEqual(result.returncode, 1)
        self.assertEqual(result.stderr, "limde-appearance: desktop preference icon-theme did not "
                                        "persist: gsettings reads '', not 'limde-light'\n")
        # The files and the mode file were written first and agree, so only the
        # preferences are still out of date.
        self.assertTrue(OUTPUTS <= self.files(self.home))
        self.assertEqual(self.mode_file.read_text(), "light\n")
        check = self.run_tool("--check")
        self.assertEqual(check.returncode, 1)
        self.assertNotIn("Needs refresh:", check.stdout)
        self.assertIn("Desktop preference needs refresh: icon-theme '' -> limde-light", check.stdout)
        self.apply()
        self.assertEqual(self.setting("icon-theme"), "'limde-light'")

    def test_a_refused_preference_names_the_reason(self):
        result = self.run_tool("--apply", FAKE_GSETTINGS="refuse")
        self.assertEqual(result.returncode, 1)
        self.assertEqual(result.stderr, "limde-appearance: could not set desktop preference "
                                        "icon-theme: gsettings: writing is not allowed\n")


if __name__ == "__main__":
    unittest.main()
